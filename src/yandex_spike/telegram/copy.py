def start_text(*, yandex_connected: bool = False, spotify_display_name: str | None = None) -> str:
    """Приветствие и предупреждение — сразу можно пользоваться меню, без галочки «согласен»."""
    yandex = "подключена" if yandex_connected else "не подключена"
    if spotify_display_name:
        spotify = f"подключён как {spotify_display_name}"
    else:
        spotify = "не подключён"
    return (
        "YaSpotSurfer переносит твою музыку из Яндекс Музыки в Spotify.\n"
        "\n"
        "Это любительский проект: я делаю его для своей коллекции и делюсь с другими. "
        "Это не сервис Яндекса и не сервис Spotify. У Яндекс Музыки нет официального "
        "способа отдать всю библиотеку другой программе, поэтому перенос неофициальный. "
        "Пользуешься на свой страх и риск.\n"
        "\n"
        f"Яндекс Музыка: {yandex}\n"
        f"Spotify: {spotify}\n"
        "\n"
        "Как это будет работать:\n"
        "1) подключаешь оба аккаунта;\n"
        "2) бот читает, какая музыка у тебя в Яндексе;\n"
        "3) ищет те же треки в Spotify и спрашивает, если не уверен;\n"
        "4) сохраняет совпадения в Spotify — сначала в отдельный плейлист для проверки, "
        "в «Любимые» только если ты явно согласишься."
    )


